    fn test_xor_cipher() {
        let mut data = vec![0x00, 0xFF, 0x55, 0xAA];
        let original = data.clone();
        
        xor_cipher(&mut data, DEFAULT_KEY);
        assert_ne!(data, original);
        
        xor_cipher(&mut data, DEFAULT_KEY);
        assert_eq!(data, original);
    }
    
