#[derive(Debug, Clone, PartialEq)]
pub struct DataRecord {
    id: u32,
    value: f64,
    timestamp: i64,
}

#[derive(Debug)]
pub enum DataError {
    InvalidId,
    InvalidValue,
    InvalidTimestamp,
    TransformationError(String),
}

impl fmt::Display for DataError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            DataError::InvalidId => write!(f, "Invalid record ID"),
            DataError::InvalidValue => write!(f, "Invalid value field"),
            DataError::InvalidTimestamp => write!(f, "Invalid timestamp"),
            DataError::TransformationError(msg) => write!(f, "Transformation error: {}", msg),
        }
    }
}

impl Error for DataError {}

impl DataRecord {
    pub fn new(id: u32, value: f64, timestamp: i64) -> Result<Self, DataError> {
        if id == 0 {
            return Err(DataError::InvalidId);
        }
        if !value.is_finite() {
            return Err(DataError::InvalidValue);
        }
        if timestamp < 0 {
            return Err(DataError::InvalidTimestamp);
        }
        
        Ok(Self { id, value, timestamp })
    }
    
    pub fn transform(&self, multiplier: f64) -> Result<Self, DataError> {
        if !multiplier.is_finite() || multiplier <= 0.0 {
            return Err(DataError::TransformationError(
                "Multiplier must be a positive finite number".to_string()
            ));
        }
        
        let new_value = self.value * multiplier;
        Ok(Self {
            id: self.id,
            value: new_value,
            timestamp: self.timestamp,
        })
    }
    
    pub fn normalize(&self, max_value: f64) -> Result<f64, DataError> {
        if max_value <= 0.0 || !max_value.is_finite() {
            return Err(DataError::TransformationError(
                "Max value must be positive and finite".to_string()
            ));
        }
        
        if self.value > max_value {
            return Err(DataError::TransformationError(
                format!("Value {} exceeds maximum {}", self.value, max_value)
            ));
        }
        
        Ok(self.value / max_value)
    }
}

pub fn process_records(records: &[DataRecord], multiplier: f64) -> Vec<Result<DataRecord, DataError>> {
    records
        .iter()
        .map(|record| record.transform(multiplier))
        .collect()
}

pub fn validate_records(records: &[DataRecord]) -> Result<(), DataError> {
    for record in records {
        if record.id == 0 {
            return Err(DataError::InvalidId);
        }
        if !record.value.is_finite() {
            return Err(DataError::InvalidValue);
        }
        if record.timestamp < 0 {
            return Err(DataError::InvalidTimestamp);
        }
    }
    Ok(())
}

