pub struct DataProcessor {
    data: Vec<f64>,
    metadata: HashMap<String, String>,
}

impl DataProcessor {
    pub fn new() -> Self {
        DataProcessor {
            data: Vec::new(),
            metadata: HashMap::new(),
        }
    }

    pub fn load_from_csv(&mut self, filepath: &str) -> Result<(), Box<dyn Error>> {
        let file = File::open(filepath)?;
        let reader = BufReader::new(file);
        
        self.data.clear();
        let mut line_count = 0;
        
        for (index, line) in reader.lines().enumerate() {
            let line = line?;
            
            if index == 0 {
                self.parse_header(&line);
                continue;
            }
            
            if let Some(value) = self.parse_numeric_value(&line) {
                self.data.push(value);
            }
            
            line_count += 1;
        }
        
        self.metadata.insert("source_file".to_string(), filepath.to_string());
        self.metadata.insert("records_processed".to_string(), line_count.to_string());
        
        Ok(())
    }
    
    fn parse_header(&mut self, header_line: &str) {
        let columns: Vec<&str> = header_line.split(',').collect();
        self.metadata.insert("column_count".to_string(), columns.len().to_string());
        
        if columns.len() > 0 {
            self.metadata.insert("first_column".to_string(), columns[0].to_string());
        }
    }
    
    fn parse_numeric_value(&self, line: &str) -> Option<f64> {
        let parts: Vec<&str> = line.split(',').collect();
        if parts.len() > 0 {
            parts[0].trim().parse::<f64>().ok()
        } else {
            None
        }
    }
    
    pub fn calculate_statistics(&self) -> HashMap<String, f64> {
        let mut stats = HashMap::new();
        
        if self.data.is_empty() {
            return stats;
        }
        
        let sum: f64 = self.data.iter().sum();
        let count = self.data.len() as f64;
        let mean = sum / count;
        
        let variance: f64 = self.data.iter()
            .map(|&x| (x - mean).powi(2))
            .sum::<f64>() / count;
        
        let min = self.data.iter().fold(f64::INFINITY, |a, &b| a.min(b));
        let max = self.data.iter().fold(f64::NEG_INFINITY, |a, &b| a.max(b));
        
        stats.insert("mean".to_string(), mean);
        stats.insert("variance".to_string(), variance);
        stats.insert("std_deviation".to_string(), variance.sqrt());
        stats.insert("min".to_string(), min);
        stats.insert("max".to_string(), max);
        stats.insert("count".to_string(), count);
        stats.insert("sum".to_string(), sum);
        
        stats
    }
    
    pub fn filter_by_threshold(&self, threshold: f64) -> Vec<f64> {
        self.data.iter()
            .filter(|&&x| x > threshold)
            .cloned()
            .collect()
    }
    
    pub fn get_metadata(&self) -> &HashMap<String, String> {
        &self.metadata
    }
    
    pub fn data_count(&self) -> usize {
        self.data.len()
    }
}

